"""
SQL Validation Module for WorkDesQ AI
Ensures that queries generated by the LLM are strictly read-only and safe to execute.
"""
import re


class SQLValidationError(ValueError):
    """Raised when an SQL query fails safety or syntax validation."""
    pass


# Forbidden DDL / DML / Administrative commands and destructive keywords
DISALLOWED_KEYWORDS = [
    r"\bINSERT\b",
    r"\bUPDATE\b",
    r"\bDELETE\b",
    r"\bDROP\b",
    r"\bALTER\b",
    r"\bTRUNCATE\b",
    r"\bREPLACE\b",
    r"\bCREATE\b",
    r"\bGRANT\b",
    r"\bREVOKE\b",
    r"\bEXEC\b",
    r"\bEXECUTE\b",
    r"\bCALL\b",
    r"\bLOCK\s+TABLES?\b",
    r"\bUNLOCK\s+TABLES?\b",
    r"\bSHUTDOWN\b",
    r"\bINTO\s+OUTFILE\b",
    r"\bINTO\s+DUMPFILE\b",
    r"\bLOAD\s+DATA\b",
]

COMPILED_DISALLOWED = [re.compile(kw, re.IGNORECASE) for kw in DISALLOWED_KEYWORDS]


def clean_query(sql: str) -> str:
    """
    Remove SQL comments and extra whitespace.
    """
    if not sql:
        return ""

    # Remove single-line comments (-- comment or # comment)
    cleaned = re.sub(r"(--[^\n]*|#[^\n]*)", " ", sql)

    # Remove multi-line comments (/* ... */)
    cleaned = re.sub(r"/\*[\s\S]*?\*/", " ", cleaned)

    return cleaned.strip()


def validate_sql(sql: str) -> None:
    """
    Validates that a SQL query is safe and strictly read-only.
    Raises SQLValidationError if unsafe.

    Safety criteria:
    1. Query must not be empty.
    2. Query must begin with SELECT or WITH (for CTE queries).
    3. Query must not contain destructive / modification keywords (DROP, DELETE, UPDATE, etc.).
    4. Multi-statement queries (separated by semicolons) are blocked to prevent chained injection.
    """
    if not isinstance(sql, str):
        raise SQLValidationError("Query must be a valid string.")

    cleaned = clean_query(sql)

    if not cleaned:
        raise SQLValidationError("Query is empty.")

    # Remove any trailing semicolons
    trimmed = cleaned.rstrip(";").strip()

    # Disallow multiple statements (unquoted semicolon in the remaining query)
    # Check if there is an internal semicolon separating statements
    in_single_quote = False
    in_double_quote = False
    for char in trimmed:
        if char == "'" and not in_double_quote:
            in_single_quote = not in_single_quote
        elif char == '"' and not in_single_quote:
            in_double_quote = not in_double_quote
        elif char == ';' and not in_single_quote and not in_double_quote:
            raise SQLValidationError(
                "Multiple SQL statements separated by semicolons are not permitted."
            )

    # Check that the query begins with a read-only keyword (SELECT or WITH)
    first_word_match = re.match(r"^\s*([A-Za-z]+)", trimmed)
    if not first_word_match:
        raise SQLValidationError("Unable to determine SQL command type.")

    first_word = first_word_match.group(1).upper()
    if first_word not in ("SELECT", "WITH", "SHOW", "DESCRIBE", "EXPLAIN"):
        raise SQLValidationError(
            f"Disallowed SQL statement '{first_word}'. Only read-only queries (SELECT) are permitted."
        )

    # Verify no prohibited commands appear anywhere in the query
    for pattern in COMPILED_DISALLOWED:
        if pattern.search(trimmed):
            matched = pattern.pattern.replace(r"\b", "").replace(r"\s+", " ")
            raise SQLValidationError(
                f"Query contains disallowed keyword '{matched}'. Only read-only queries are permitted."
            )


def is_safe_sql(sql: str) -> bool:
    """
    Check if a query is safe without raising an exception.
    Returns True if valid, False otherwise.
    """
    try:
        validate_sql(sql)
        return True
    except SQLValidationError:
        return False
